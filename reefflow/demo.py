def make_rock_mesh(h: float = 0.004):
    verts, faces, off = [], [], 0
    for isl in ISLANDS:
        blobs = isl["blobs"]
        lo = np.min([np.subtract(b["center"], np.multiply(b["radii"], 1.5)) for b in blobs], axis=0)
        hi = np.max([np.add(b["center"], np.multiply(b["radii"], 1.5)) for b in blobs], axis=0)
        lo[2] = SAND - 0.03                     # bury the base in the sand
        v, f = G.sdf_to_mesh(lambda P, b=blobs, s=isl["seed"]: G.rock_sdf(P, b, s), lo, hi, h)
        verts.append(v); faces.append(f + off); off += len(v)
    return np.vstack(verts), np.vstack(faces)


def write_demo(directory) -> Path:
    d = Path(directory)
    d.mkdir(parents=True, exist_ok=True)
    v, f = make_rock_mesh()
    G.save_stl(d / "rock.stl", v, f, unit="mm")
    p = d / "demo_75gal.yaml"
    p.write_text(PROJECT_YAML, encoding="utf-8")
    return p
